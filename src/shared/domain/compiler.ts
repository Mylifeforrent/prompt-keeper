export const APPROXIMATION_NOTICE =
  'This preview is an approximation of how the target tool loads instructions. The tool itself is authoritative.'

export interface CompileTarget {
  id: string
  label: string
  format: ContractFormat | 'plain-md'
  merge: 'single-file' | 'per-contract'
  supports: { globs: boolean; modelDecision: boolean; manual: boolean; imports: boolean }
  maxBytes?: number
}

export function utf8Bytes(text: string): number {
  return new TextEncoder().encode(text).length
}

export function managedBlock(model: ContractFileModel, sourcePath: string): string {
  const id = model.id
  return [
    `<!-- pk:begin ${id} -->`,
    `<!-- Prompt Keeper managed block. Source: ${sourcePath}. Edits inside this block are reported as drift. -->`,
    `## ${model.title}`,
    '',
    model.body.trim(),
    `<!-- pk:end ${id} -->`,
  ].join('\n')
}

export interface ManagedParseResult {
  ok: boolean
  error?: string
  segments: Array<{ type: 'text'; text: string } | { type: 'block'; id: string; text: string }>
}

const BEGIN_RE = /<!-- pk:begin ([A-Za-z0-9_:-]+) -->/g
const END_RE = /<!-- pk:end ([A-Za-z0-9_:-]+) -->/g

export function parseManagedFile(text: string): ManagedParseResult {
  const segments: ManagedParseResult['segments'] = []
  const seen = new Set<string>()
  let cursor = 0
  let openId: string | null = null
  let openStart = 0

  const lines = text.split('\n')
  let offset = 0
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]
    const begin = line.match(/^<!-- pk:begin ([A-Za-z0-9_:-]+) -->$/)
    const end = line.match(/^<!-- pk:end ([A-Za-z0-9_:-]+) -->$/)
    if (begin) {
      if (openId) {
        return { ok: false, error: `Managed block "${openId}" is not closed before "${begin[1]}".`, segments }
      }
      if (seen.has(begin[1])) {
        return { ok: false, error: `Managed block "${begin[1]}" appears more than once.`, segments }
      }
      if (offset > cursor) segments.push({ type: 'text', text: text.slice(cursor, offset) })
      openId = begin[1]
      openStart = offset
      seen.add(begin[1])
    } else if (end) {
      if (!openId) {
        return { ok: false, error: `Managed block end "${end[1]}" has no matching begin.`, segments }
      }
      if (end[1] !== openId) {
        return { ok: false, error: `Managed block "${openId}" is closed by "${end[1]}".`, segments }
      }
      const blockEnd = offset + line.length
      segments.push({ type: 'block', id: openId, text: text.slice(openStart, blockEnd) })
      cursor = blockEnd
      openId = null
    }
    offset += line.length + 1
  }

  if (openId) {
    return { ok: false, error: `Managed block "${openId}" is not closed.`, segments }
  }
  if (cursor < text.length) segments.push({ type: 'text', text: text.slice(cursor) })
  return { ok: true, segments }
}

const GENERATION_MARKER =
  '<!-- Generated by Prompt Keeper. Content outside managed blocks is preserved; managed blocks are rewritten. -->'

export interface UpsertResult {
  text: string
  error?: string
}

/**
 * Replace or append managed blocks while preserving all outside content.
 * When the existing file is not parseable, the caller must treat it as drifted.
 */
export function upsertManagedBlocks(
  existing: string,
  blocks: Array<{ id: string; text: string }>,
  removeIds: string[] = [],
  order: string[] = [],
): UpsertResult {
  const parsed = parseManagedFile(existing)
  if (!parsed.ok) return { text: existing, error: parsed.error }

  const wanted = new Map(blocks.map((block) => [block.id, block.text]))
  const remove = new Set(removeIds)
  const written = new Set<string>()
  const output: string[] = []

  for (const segment of parsed.segments) {
    if (segment.type === 'text') {
      output.push(segment.text)
      continue
    }
    if (remove.has(segment.id)) continue
    const replacement = wanted.get(segment.id)
    if (replacement !== undefined) {
      output.push(replacement)
      written.add(segment.id)
    } else {
      output.push(segment.text)
    }
  }

  const orderIndex = new Map(order.map((id, index) => [id, index]))
  const missing = blocks
    .filter((block) => !written.has(block.id) && !remove.has(block.id))
    .sort((a, b) => (orderIndex.get(a.id) ?? 0) - (orderIndex.get(b.id) ?? 0))

  let text = output.join('')
  if (!text.trim()) text = `${GENERATION_MARKER}\n`
  if (missing.length) {
    const prefix = text.endsWith('\n') ? text : `${text}\n`
    text = `${prefix}\n${missing.map((block) => block.text).join('\n\n')}\n`
  }
  return { text }
}

function frontier(description: string): string {
  return description.replace(/\r?\n/g, ' ').trim()
}

function frontmatterFor(model: ContractFileModel, target: CompileTarget): string {
  const description = frontier(model.activation.description || model.description || model.title)
  const globs = model.activation.globs
  switch (target.format) {
    case 'cursor-mdc':
      return [
        '---',
        `description: ${JSON.stringify(description)}`,
        `globs: ${JSON.stringify(globs)}`,
        `alwaysApply: ${model.activation.mode === 'always' ? 'true' : 'false'}`,
        '---',
      ].join('\n')
    case 'windsurf-rule': {
      const trigger: Record<ContractActivationMode, string> = {
        always: 'always_on',
        glob: 'glob',
        model: 'model_decision',
        manual: 'manual',
      }
      return [
        '---',
        `trigger: ${trigger[model.activation.mode]}`,
        `globs: ${JSON.stringify(globs)}`,
        `description: ${JSON.stringify(description)}`,
        '---',
      ].join('\n')
    }
    case 'copilot-path': {
      const applyTo = globs.length
        ? globs.join(', ')
        : model.pathPrefix
          ? `${model.pathPrefix}/**`
          : '**'
      return ['---', `applyTo: ${JSON.stringify(applyTo)}`, '---'].join('\n')
    }
    default:
      return ''
  }
}

/** Render one contract for a per-contract target or a managed block for a single-file target. */
export function compileContract(model: ContractFileModel, target: CompileTarget, sourcePath: string): string {
  if (target.merge === 'single-file') return managedBlock(model, sourcePath)
  const frontmatter = frontmatterFor(model, target)
  const body = model.body.trim()
  return frontmatter ? `${frontmatter}\n\n${body}\n` : `${body}\n`
}

export function compiledFileName(model: ContractFileModel, target: CompileTarget): string {
  const slug = safePathSegment(contractSlug(model), model.id)
  switch (target.format) {
    case 'cursor-mdc':
      return `${slug}.mdc`
    case 'copilot-path':
      return `${slug}.instructions.md`
    case 'windsurf-rule':
    case 'plain-md':
    default:
      return `${slug}.md`
  }
}

export interface CompileFileSetInput {
  contracts: Array<{ model: ContractFileModel; sourcePath: string }>
  target: CompileTarget
  existingFiles?: Record<string, string>
  removeIds?: string[]
}

export function compileFileSet(input: CompileFileSetInput): { files: CompiledFile[]; warnings: string[] } {
  const warnings: string[] = []
  if (input.target.merge === 'single-file') {
    const blocks = input.contracts.map((entry) => ({
      id: entry.model.id,
      text: compileContract(entry.model, input.target, entry.sourcePath),
    }))
    const existing = input.existingFiles?.[input.target.id] ?? ''
    const merged = upsertManagedBlocks(
      existing,
      blocks,
      input.removeIds,
      input.contracts.map((entry) => entry.model.id),
    )
    if (merged.error) warnings.push(merged.error)
    const content = merged.text
    return {
      files: [
        {
          targetId: input.target.id,
          path: input.target.id,
          content,
          bytes: utf8Bytes(content),
        },
      ],
      warnings,
    }
  }

  const files = input.contracts.map((entry) => {
    const content = compileContract(entry.model, input.target, entry.sourcePath)
    return {
      targetId: input.target.id,
      path: `${input.target.id}/${compiledFileName(entry.model, input.target)}`,
      content,
      bytes: utf8Bytes(content),
    }
  })
  return { files, warnings }
}

export interface ResolveInput {
  contracts: Array<{ model: ContractFileModel; sourcePath: string; updatedAt: string }>
  target: CompileTarget
  scope: 'project' | 'global'
  samplePath?: string
  contractIds?: string[]
}

function scopeMatches(model: ContractFileModel, scope: 'project' | 'global'): boolean {
  return scope === 'global' ? model.scope === 'user' : model.scope === 'project' || model.scope === 'path'
}

function matchesSamplePath(model: ContractFileModel, samplePath?: string): boolean {
  if (!samplePath) return true
  const normalized = samplePath.replace(/\\/g, '/').replace(/^\.?\//, '')
  if (model.scope === 'path' && model.pathPrefix) {
    const prefix = model.pathPrefix.replace(/\\/g, '/').replace(/\/+$/, '')
    if (normalized !== prefix && !normalized.startsWith(`${prefix}/`)) return false
  }
  if (model.activation.mode === 'glob' && model.activation.globs.length) {
    return model.activation.globs.some((glob) => {
      try {
        return picomatch(glob, { dot: true })(normalized)
      } catch {
        return false
      }
    })
  }
  return true
}

export function resolveContracts(input: ResolveInput): ResolvedPreview {
  const included: ResolvedContractEntry[] = []
  const skipped: SkippedContractEntry[] = []
  const warnings: string[] = []
  const selected = input.contractIds ? new Set(input.contractIds) : null
  let totalBytes = 0
  const prioritySeen = new Map<number, number>()

  const ordered = [...input.contracts].sort((a, b) => {
    const priority = b.model.priority - a.model.priority
    if (priority !== 0) return priority
    const updated = a.updatedAt.localeCompare(b.updatedAt)
    if (updated !== 0) return updated
    return a.model.id.localeCompare(b.model.id)
  })

  for (const entry of ordered) {
    const { model } = entry
    if (!model.targetIds.includes(input.target.id)) {
      skipped.push({
        contractId: model.id,
        title: model.title,
        reason: `Target "${input.target.label}" is not selected for this contract.`,
        code: 'target-not-selected',
      })
      continue
    }
    if (!scopeMatches(model, input.scope)) {
      skipped.push({
        contractId: model.id,
        title: model.title,
        reason:
          input.scope === 'global'
            ? 'Only user-scoped contracts are written to global targets.'
            : 'This contract is user-scoped and belongs to global targets.',
        code: 'path-scope-mismatch',
      })
      continue
    }
    if (selected && !selected.has(model.id)) {
      skipped.push({
        contractId: model.id,
        title: model.title,
        reason: 'Not part of the current selection.',
        code: 'target-not-selected',
      })
      continue
    }
    if (model.scope === 'path' && !model.pathPrefix) {
      skipped.push({
        contractId: model.id,
        title: model.title,
        reason: 'Path scope requires a directory prefix.',
        code: 'path-scope-mismatch',
      })
      continue
    }

    switch (model.activation.mode) {
      case 'glob':
        if (!input.target.supports.globs) {
          skipped.push({
            contractId: model.id,
            title: model.title,
            reason: `${input.target.label} has no path-based activation; the contract is skipped instead of silently becoming always-on.`,
            code: 'activation-unsupported',
          })
          continue
        }
        break
      case 'model':
        if (!input.target.supports.modelDecision) {
          skipped.push({
            contractId: model.id,
            title: model.title,
            reason: `${input.target.label} cannot let the model decide relevance.`,
            code: 'activation-unsupported',
          })
          continue
        }
        break
      case 'manual':
        if (!input.target.supports.manual) {
          skipped.push({
            contractId: model.id,
            title: model.title,
            reason: `${input.target.label} has no manual reference mode.`,
            code: 'activation-unsupported',
          })
          continue
        }
        skipped.push({
          contractId: model.id,
          title: model.title,
          reason: 'Manual activation never enters the context automatically.',
          code: 'manual-only',
        })
        continue
      default:
        break
    }

    if (!matchesSamplePath(model, input.samplePath)) {
      skipped.push({
        contractId: model.id,
        title: model.title,
        reason: input.samplePath
          ? `The sample path "${input.samplePath}" is outside the contract's activation paths.`
          : 'The contract does not match the sample path.',
        code: model.scope === 'path' ? 'path-scope-mismatch' : 'glob-not-matched',
      })
      continue
    }

    const rendered = compileContract(model, input.target, entry.sourcePath)
    const bytes = utf8Bytes(rendered)
    totalBytes += bytes
    included.push({
      contractId: model.id,
      title: model.title,
      sourcePath: entry.sourcePath,
      reason: reasonFor(model),
      bytes,
      revisionId: '',
      activationMode: model.activation.mode,
    })
    prioritySeen.set(model.priority, (prioritySeen.get(model.priority) ?? 0) + 1)
  }

  for (const [priority, count] of prioritySeen) {
    if (count > 1) warnings.push(`${count} contracts share priority ${priority}; order is deterministic by updated time, then ID.`)
  }

  const budgetExceeded = !!input.target.maxBytes && totalBytes > input.target.maxBytes
  if (budgetExceeded) {
    warnings.push(
      `Compiled output is ${totalBytes} bytes, above the ${input.target.maxBytes} byte budget for ${input.target.label}. The target may truncate or ignore content.`,
    )
  }

  const compiledFilePaths =
    input.target.merge === 'single-file'
      ? [input.target.id]
      : included.map((entry) => {
          const model = input.contracts.find((c) => c.model.id === entry.contractId)!.model
          return `${input.target.id}/${compiledFileName(model, input.target)}`
        })

  return {
    targetId: input.target.id,
    scope: input.scope,
    ...(input.samplePath ? { samplePath: input.samplePath } : {}),
    included,
    skipped,
    totalBytes,
    ...(input.target.maxBytes ? { maxBytes: input.target.maxBytes } : {}),
    budgetExceeded,
    warnings,
    compiledFilePaths,
    approximationNotice: APPROXIMATION_NOTICE,
  }
}

function reasonFor(model: ContractFileModel): string {
  switch (model.activation.mode) {
    case 'glob':
      return `Path activation: ${model.activation.globs.join(', ') || 'no glob'}`
    case 'model':
      return `Model decision: ${model.activation.description || 'no description'}`
    case 'manual':
      return 'Manual reference only'
    default:
      return model.scope === 'path' ? `Always on within ${model.pathPrefix ?? 'the scope'}` : 'Always on'
  }
}

export function resolvePathForTarget(
  targetId: string,
  format: ContractFormat | 'plain-md',
  merge: 'single-file' | 'per-contract',
  basePath: string,
  slug: string,
): string {
  if (merge === 'single-file') return basePath
  const fileName = (() => {
    switch (format) {
      case 'cursor-mdc':
        return `${slug}.mdc`
      case 'copilot-path':
        return `${slug}.instructions.md`
      default:
        return `${slug}.md`
    }
  })()
  return `${basePath.replace(/[\\/]+$/, '')}/${fileName}`
}
